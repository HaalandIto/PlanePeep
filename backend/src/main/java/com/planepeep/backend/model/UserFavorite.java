package com.planepeep.backend.model;

import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.PostUpdate;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import java.time.Instant;

/**
 * Represents one aircraft saved by one user.
 *
 * <p>The record stores:
 * - unique id
 * - reference to the owning user
 * - the ICAO24 of the aircraft (externalItemId)
 * - an optional user-defined name
 * - an optional position index for ordering favorites in the UI
 * - timestamps for when the favorite was created and last updated
 */
@Entity
@Table(
    name = "user_favorites",
    uniqueConstraints = @UniqueConstraint(
        name = "uq_user_external_item",
        columnNames = { "user_id", "external_item_id" }
    )
)
public class UserFavorite {

    /**
     * The unique ID of this favorite record. Generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "favorite_id")
    private Long favoriteId;

    /**
     * User owning the favorite. Many favorites can belong to one user. Corresponds to JWT.
     */
    @JsonIgnore
    @ManyToOne(optional = false, fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /**
     * Refers ONLY to ICAO24. Unique per user.
     */
    @Column(name = "external_item_id", nullable = false)
    private String externalItemId;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /**
     * Display name. Also used by the rename PATCH endpoint.
     */
    @Column(name = "name", nullable = false)
    private String name;

    /**
     * Order field. Also used by the position PATCH endpoint.
     */
    @Column(name = "position_index", nullable = false)
    private Integer sortOrder = 0;

    /**
     * Optional aircraft typecode field.
     */
    @Column(name = "typecode")
    private String typecode;

    /**
     * Optional tail number / registration field. If present used as primary display name instead of ICAO24.
     */
    @Column(name = "tail_number")
    private String tailNumber;

    public UserFavorite() {}

    public Long getFavoriteId() {
        return favoriteId;
    }

    public User getUser() {
        return user;
    }

    public String getExternalItemId() {
        return externalItemId;
    }

    public String getName() {
        return name;
    }

    public Integer getSortOrder() {
        return sortOrder;
    }

    public void setFavoriteId(Long favoriteId) {
        //TODO probably should not have this setter, but needed for tests
        this.favoriteId = favoriteId;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public void setExternalItemId(String externalItemId) {
        this.externalItemId = externalItemId;
    }

    public void setName(String name) {
        this.name = name;
    }

    public void setSortOrder(Integer SortOrder) {
        this.sortOrder = SortOrder;
    }

    // tail number / registration (first default)

    public String getTailNumber() {
        return tailNumber;
    }

    public void setTailNumber(String tailNumber) {
        this.tailNumber = tailNumber;
    }

    // last updated (second default)

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    @PrePersist
    protected void onCreate() {
        this.createdAt = Instant.now();
        this.updatedAt = Instant.now();
    }

    @PostUpdate
    protected void onUpdate() {
        this.updatedAt = Instant.now();
    }

    public String getTypecode() {
        return typecode;
    }

    public void setTypecode(String typecode) {
        this.typecode = typecode;
    }
}
